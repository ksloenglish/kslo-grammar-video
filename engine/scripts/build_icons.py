"""Build proto/icons.js from the saved open-source SVGs (run after adding an icon).
Phosphor Icons core v2.1.1 duotone (MIT, design/phosphor/<name>.svg) -> PH[name] = inner markup (viewBox 0 0 256 256).
Microsoft Fluent Emoji Flat (MIT, design/fluent_<name>.svg) -> ART[name] = full <svg> markup."""
import glob, json, os, re
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "design")
ph = {}
for f in sorted(glob.glob(f"{D}/phosphor/*.svg")):
    s = open(f).read()
    n = os.path.basename(f)[:-4]
    inner = lambda x: re.sub(r"^<svg[^>]*>|</svg>\s*$", "", x.strip())
    tint = "".join(re.findall(r'<path[^>]*opacity="0\.2"[^>]*/>', s)).replace('opacity="0.2"', 'opacity="0.3"')
    bold = f"{D}/phosphor_bold/{n}.svg"          # bold outline + duotone tint reads better at 40-90 px
    ph[n] = tint + inner(open(bold).read()) if os.path.exists(bold) else inner(s)
art = {}
for f in sorted(glob.glob(f"{D}/fluent_*.svg")):
    s = open(f).read().strip()
    tag = re.match(r"<svg[^>]*>", s).group(0)
    s = s.replace(tag, re.sub(r'\s(width|height)="[^"]*"', "", tag).replace("<svg ", '<svg width="100%" height="100%" ', 1), 1)
    art[os.path.basename(f)[7:-4]] = s
out = os.path.join(D, "..", "proto", "icons.js")
open(out, "w").write("// Generated by scripts/build_icons.py. Phosphor Icons (MIT) duotone + Microsoft Fluent Emoji Flat (MIT).\n"
                     f"const PH = {json.dumps(ph)};\nconst ART = {json.dumps(art)};\n")
print(out, len(ph), "phosphor:", " ".join(ph), "| art:", " ".join(art))
